"""A model's JSON as ``model_dump(mode="json")`` writes it, keyed as a job's result is.

A job's result is its output model's serialization, ``model_dump(mode="json", by_alias=True)``:
what temporalio's pydantic converter writes for a workflow entry's result, and what the
contract describes (decisions I38). A bound handler's reply arrives as temporal-agent-harness
publishes it, ``model_dump(mode="json")``: the same serialization -- computed fields in,
excluded fields out, serializers applied -- keyed by field name instead (by alias for a model
whose config says ``serialize_by_alias``). :func:`by_alias` re-keys it and changes nothing
else. Validating the reply and dumping it again would not be the same: it refuses a reply
without its excluded field, and applies a serializer to what that serializer already wrote.

The keys come from pydantic: the model's serialization-mode schema, generated by alias, each
object noting the key ``model_dump(mode="json")`` writes each of its members under. The same
schema picks a union's branch (an ``Optional``'s by ``null``, a tagged union's by the branch
whose ``const`` tag the value carries). It is Kontra's own and never published.
"""

from __future__ import annotations

import functools
from collections.abc import Iterable, Mapping
from typing import Any, cast

from pydantic import BaseModel
from pydantic.json_schema import JsonSchemaValue, models_json_schema
from pydantic_core import core_schema

from kontra.contract.derive import _Generator  # pyright: ignore[reportPrivateUsage]

__all__ = ["by_alias"]

#: Where the schema below notes each object's keys: ``{result key: key in the dump}``.
_KEYS = "x-kontra-keys"
_DEFS = "#/$defs/"
#: A value is walked by following references; a model's depth bounds it, this bounds a bug.
_MAX_REFS = 64

_Field = core_schema.ModelField | core_schema.DataclassField | core_schema.TypedDictField


class _Keyed(_Generator):
    """The derivation's generator, noting the keys of each object it writes."""

    def _note(
        self,
        js: JsonSchemaValue,
        fields: Iterable[tuple[str, _Field]],
        computed: Iterable[core_schema.ComputedField],
    ) -> JsonSchemaValue:
        # model_dump(mode="json") keys a member by name, or by alias where the model's own
        # config says serialize_by_alias (pydantic >= 2.11); by_alias=True always by alias.
        own = bool(getattr(self._config, "serialize_by_alias", False))
        keys: dict[str, str] = {}
        for name, field in fields:
            if self.field_is_present(field):
                alias = field.get("serialization_alias")
                key = alias if isinstance(alias, str) else name
                keys[key] = key if own else name
        for cf in computed:
            name = cf["property_name"]
            alias = cf.get("alias")
            key = alias if isinstance(alias, str) else name
            keys[key] = key if own else name
        js[_KEYS] = keys
        return js

    def model_fields_schema(self, schema: core_schema.ModelFieldsSchema) -> JsonSchemaValue:
        return self._note(
            super().model_fields_schema(schema),
            schema["fields"].items(),
            schema.get("computed_fields", []),
        )

    def dataclass_args_schema(self, schema: core_schema.DataclassArgsSchema) -> JsonSchemaValue:
        return self._note(
            super().dataclass_args_schema(schema),
            ((f["name"], f) for f in schema["fields"]),
            schema.get("computed_fields", []),
        )

    def typed_dict_schema(self, schema: core_schema.TypedDictSchema) -> JsonSchemaValue:
        return self._note(
            super().typed_dict_schema(schema),
            schema["fields"].items(),
            schema.get("computed_fields", []),
        )


@functools.cache
def _schema(model: type[BaseModel]) -> tuple[dict[str, Any], dict[str, Any]]:
    """The model's root (a reference) and its definitions, in serialization mode."""
    key_map, generated = models_json_schema(
        [(model, "serialization")], ref_template=_DEFS + "{model}", schema_generator=_Keyed
    )
    defs = cast(dict[str, Any], generated.get("$defs", {}))
    return dict(key_map[(model, "serialization")]), defs


def by_alias(model: type[BaseModel], dumped: Any) -> Any:
    """``dumped``, ``model_dump(mode="json")`` of a ``model``, as
    ``model_dump(mode="json", by_alias=True)`` of the same instance: every object's members
    re-keyed from the key the first writes to the key the second does. Keys it does not
    know (``extra="allow"``, or a key already written by alias) are kept as they are; a value
    of another shape comes back re-keyed as far as it matches, and is then for the
    contract's validator to refuse."""
    root, defs = _schema(model)
    return _Walker(defs).walk(dumped, root, 0)


class _Walker:
    def __init__(self, defs: Mapping[str, Any]) -> None:
        self._defs = defs

    def _resolve(self, node: Any, refs: int) -> tuple[Mapping[str, Any], int]:
        """``node`` with its ``$ref`` followed (its siblings constrain; they rename nothing)."""
        while True:
            schema = cast(Mapping[str, Any], node) if isinstance(node, Mapping) else {}
            ref = schema.get("$ref")
            if not (isinstance(ref, str) and ref.startswith(_DEFS)) or refs >= _MAX_REFS:
                return schema, refs
            node = self._defs.get(ref.removeprefix(_DEFS))
            refs += 1

    def walk(self, value: Any, node: Any, refs: int) -> Any:
        schema, refs = self._resolve(node, refs)
        if value is None:
            return None
        for key in ("anyOf", "oneOf"):
            branches = schema.get(key)
            if isinstance(branches, list):
                branch = self._branch(value, cast(list[Any], branches), refs)
                return value if branch is None else self.walk(value, branch, refs)
        parts = schema.get("allOf")
        if isinstance(parts, list) and len(cast(list[Any], parts)) == 1:
            return self.walk(value, cast(list[Any], parts)[0], refs)
        if isinstance(value, Mapping):
            obj = cast(Mapping[str, Any], value)
            props_raw = schema.get("properties")
            props = cast(Mapping[str, Any], props_raw) if isinstance(props_raw, Mapping) else {}
            extra = schema.get("additionalProperties")
            renamed = _renamed(schema)
            out: dict[str, Any] = {}
            for k, v in obj.items():
                key = renamed.get(k, k)
                out[key] = self.walk(v, props.get(key, extra), refs)
            return out
        if isinstance(value, list):
            items = schema.get("items")
            return [self.walk(v, items, refs) for v in cast(list[Any], value)]
        return value

    def _branch(self, value: Any, branches: list[Any], refs: int) -> Any:
        """The one branch that describes ``value``, or None when no single one does."""
        options = [b for b in branches if self._resolve(b, refs)[0].get("type") != "null"]
        if len(options) == 1:
            return options[0]
        fitting = [b for b in options if self._fits(value, b, refs)]
        return fitting[0] if len(fitting) == 1 else None

    def _fits(self, value: Any, node: Any, refs: int) -> bool:
        """An object branch whose ``const`` members the value carries, under their keys in
        the dump, and that knows every key the value has (unless it is open)."""
        schema, _ = self._resolve(node, refs)
        if not isinstance(value, Mapping) or schema.get("type") != "object":
            return False
        obj = cast(Mapping[str, Any], value)
        props_raw = schema.get("properties")
        props = cast(Mapping[str, Any], props_raw) if isinstance(props_raw, Mapping) else {}
        renamed = _renamed(schema)
        dumped_as = {key: k for k, key in renamed.items()}
        for key, sub in props.items():
            tag = self._resolve(sub, refs)[0]
            if "const" in tag and obj.get(dumped_as.get(key, key)) != tag["const"]:
                return False
        if schema.get("additionalProperties") in (None, False):
            return all(renamed.get(k, k) in props for k in obj)
        return True


def _renamed(schema: Mapping[str, Any]) -> dict[str, str]:
    """``{key in the dump: result key}`` of one object's schema."""
    keys = schema.get(_KEYS)
    if not isinstance(keys, Mapping):
        return {}
    return {str(dumped): str(result) for result, dumped in cast(Mapping[str, Any], keys).items()}
